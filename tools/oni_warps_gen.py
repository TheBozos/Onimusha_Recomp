"""oni_warps_gen.py <IMAGE/RDT dir> <out.cpp>: the room warp's destinations (runtime/oni_cheats.cpp), from the doors in
the player's disc's room files. Game-derived: generated into the build, never committed.

A room file (IMAGE/RDT/ROOMsrr.RDT: stage s, room rr in hex) holds the room's event script; a door is set by the
script's opcode 0x39 (an AOT with data): the opcode, the AOT's slot (0..31), the AOT (sys_sub.c's _SCE_AOT: Id 1 for a
door, Type, nFloor, Super, X, Z, W, D) and the door (_IN_DOOR_WORK, 18 bytes: Next_pos_x / y / z, Next_dir_y,
Next_stage, Next_room, Next_cut, Next_nfloor, Dtex_type, Door_type, Lock_se_no, Key_id, Key_type, Door_no). Each door
is a way into its destination room with a spawn point the game itself uses; the warp list is one such door per
destination (a door with a position: the scripted transitions carry none), the destination's room file existing.
"""
import glob
import os
import struct
import sys


def cut_count(d):
    """The room's cuts: the LINK section holding the cut table (16 bytes a cut: the Z buffer's and the IPU picture's
    offsets and sizes in the room's BGS file, each starting where the previous ended, rounded up to 0x800)."""
    if d[:4] != b"LINK":
        return 0
    best = 0
    for k in range(struct.unpack_from("<I", d, 4)[0]):
        _flag, off, size = struct.unpack_from("<3I", d, 8 + 12 * k)
        if size < 16 or size % 16 or off + size > len(d):
            continue
        expect, cuts = 0, 0
        for c in range(size // 16):
            zoff, zsize, ioff, isize = struct.unpack_from("<4I", d, off + 16 * c)
            ioff &= 0x0FFFFFFF  # bits 28-30: the cut's background movie (Cut_change)
            if zoff != expect or zsize == 0 or isize == 0 or ioff != (zoff + zsize + 0x7FF) & ~0x7FF:
                break
            expect = (ioff + isize + 0x7FF) & ~0x7FF
            cuts += 1
        best = max(best, cuts)  # (a table may be padded past its last cut)
    return best


def doors(rdt_dir):
    files = {os.path.basename(f).upper(): f for f in glob.glob(os.path.join(rdt_dir, "*.RDT"))}
    by_dest = {}
    cuts = {name: cut_count(open(files[name], "rb").read()) for name in files}
    for name in sorted(files):
        d = open(files[name], "rb").read()
        source = (int(name[4]), int(name[5:7], 16))
        for i in range(len(d) - 34):
            if d[i] != 0x39 or d[i + 1] >= 32 or d[i + 2] != 1:
                continue
            a = i + 2
            x, z, w, depth = struct.unpack_from("<hhHH", d, a + 4)
            if w == 0 or depth == 0 or w > 30000 or depth > 30000:
                continue
            nx, ny, nz, nd = struct.unpack_from("<hhhh", d, a + 12)
            stage, room, cut = d[a + 20], d[a + 21], d[a + 22]
            floor = struct.unpack_from("<b", d, a + 23)[0]
            dtex, dtype = d[a + 24], d[a + 25]
            dest = "ROOM%d%02X.RDT" % (stage, room)
            if dest not in files or cut > 48 or not (-2 <= floor <= 6) or abs(ny) > 10000 or not (0 <= nd <= 4096):
                continue
            if nx == 0 and ny == 0 and nz == 0:
                continue  # a scripted transition: no spawn point
            if cuts[dest] and cut >= cuts[dest]:
                continue  # a cut the room has only in another story state (cut_replace): not a warp
            by_dest.setdefault((stage, room), (stage, room, cut, nx, ny, nz, nd, floor, dtex, dtype, source))
    return [by_dest[k] for k in sorted(by_dest)]


def main():
    if len(sys.argv) != 3:
        print(__doc__, file=sys.stderr)
        return 2
    rows = doors(sys.argv[1])
    lines = ["// Generated by tools/oni_warps_gen.py from the player's disc (IMAGE/RDT): do not edit, never commit.",
             '#include "oni_cheats.h"', "", "namespace oni::cheats", "{", "    const Warp kWarps[] = {"]
    for (stage, room, cut, x, y, z, d, floor, dtex, dtype, (fs, fr)) in rows:
        lines.append(f"        {{{stage}, {room}, {cut}, {x}, {y}, {z}, {d}, {floor}, {dtex}, {dtype}, {fs}, {fr}}},")
    lines += ["    };", "    const size_t kWarpCount = sizeof(kWarps) / sizeof(kWarps[0]);", "}", ""]
    open(sys.argv[2], "w", newline="\n").write("\n".join(lines))
    print(f"{len(rows)} warp destinations")
    return 0


if __name__ == "__main__":
    sys.exit(main())
