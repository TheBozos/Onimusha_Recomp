"""oni_modules_gen.py <oni_modules.txt> <gen dir> <out.cpp>: the overlay modules' registration.

Writes oni::registerModules(Runtime &), which adds every prepared module (tools/oni_prepare.py) to the runtime's
function registry: its generated tables, its address slot and its 64-byte resident identity (embedded, so the
executable does not need the prepared files at run time). A module's functions are callable only while the bytes at
its load address match its identity (BozoEngine runtime.h, FunctionTable::addModule).
"""
import pathlib
import sys

# The slots the game loads modules into: (start, end) of the address range each module shares with its siblings.
SLOTS = [(0x4BA780, 0x4C9500), (0x4C9500, 0x4D8280), (0x4D8280, 0x4DCA80), (0x2BF200, 0x2C3780)]


def main() -> int:
    listing, gen, out = sys.argv[1:4]
    gen = pathlib.Path(gen)
    modules = []
    for line in pathlib.Path(listing).read_text().splitlines():
        name, load, end = line.split()
        load, end = int(load, 0), int(end, 0)
        slot = next(((lo, hi) for lo, hi in SLOTS if lo <= load < hi), None)
        if slot is None or end > slot[1]:
            print(f"{name}: {load:#x}-{end:#x} outside the known overlay slots", file=sys.stderr)
            return 1
        identity = (gen / f"{name}.identity").read_bytes()
        modules.append((name, slot, identity))
    lines = ['// Generated by tools/oni_modules_gen.py from the player\'s disc: never commit.',
             '#include "bozo/runtime.h"', '#include <cstddef>', '#include <cstdint>', '#include <vector>', '']
    for name, _, _ in modules:
        lines += [f'extern const BozoFunctionEntry {name}_function_table[];',
                  f'extern const size_t {name}_function_count;',
                  f'extern const BozoResumeEntry {name}_resume_table[];',
                  f'extern const size_t {name}_resume_count;']
    lines += ['', 'namespace oni', '{', '    size_t registerModules(Runtime &rt)', '    {',
              '        uint8_t *ram = rt.memory.ram();']
    for name, (lo, hi), identity in modules:
        data = ', '.join(f'0x{b:02x}' for b in identity)
        lines += [f'        rt.functions.addModule(0x{lo:x}, 0x{hi:x}, ram + 0x{lo:x}, std::vector<uint8_t>{{{data}}},',
                  f'                               {name}_function_table, {name}_function_count, '
                  f'{name}_resume_table, {name}_resume_count);']
    lines += [f'        return {len(modules)};', '    }', '} // namespace oni', '']
    pathlib.Path(out).write_text('\n'.join(lines), encoding='utf-8')
    return 0


if __name__ == '__main__':
    sys.exit(main())
